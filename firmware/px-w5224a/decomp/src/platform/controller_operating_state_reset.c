#include "controller_operating_state_reset.h"
#include "firmware_memory.h"

#define PLEXTOR_BINDING_SECTION 1
#include "bindings/platform/controller_operating_state_reset_bindings.h"
#undef PLEXTOR_BINDING_SECTION

static void WriteOperatingResetWord(u16 address, u16 value)
{
    FirmwareWriteNearU16(address, value);
}

/* RAM:fb1f9a */
void ResetControllerOperatingState(void)
{
    u8 saved_p1_bit1;
    u8 saved_p1_bit0;

    OPERATING_RESET_CONFIGURE_PORTS();
    if((FirmwareReadNear8(FW_NEAR_UNKNOWN_1304) & 1u) == 1u)
    {
        OPERATING_RESET_STROBE(FW_CONTROLLER_UNKNOWN_01803B, 0x88u);
        OPERATING_RESET_STROBE(FW_CONTROLLER_UNKNOWN_018079, 0x10u);
        FirmwareWriteNear8(FW_NEAR_UNKNOWN_1008, 0u);
        FirmwareWriteNear8(FW_NEAR_UNKNOWN_FBEC, 1u);
        OPERATING_RESET_CONFIGURE_PARAMETERS(0u);
        OPERATING_RESET_APPLY_D1();
        FirmwareWriteNear8(FW_NEAR_UNKNOWN_FC0F, 0xa0u);
        if(FirmwareReadNear8(FW_NEAR_UNKNOWN_FAC0) != 0xffu)
            FirmwareWriteNear8(FW_NEAR_UNKNOWN_FC0F, (u8)(FirmwareReadNear8(FW_NEAR_UNKNOWN_FAC0) + 0xd8u));
    }

    OPERATING_RESET_INITIALIZE_BLOCK();
    OPERATING_RESET_RESET_PARAMETERS();
    FirmwareWriteNear8(FW_NEAR_UNKNOWN_1304, (u8)(FirmwareReadNear8(FW_NEAR_UNKNOWN_1304) & 0xf7u));
    FirmwareWriteNear8(FW_NEAR_UNKNOWN_1301, (u8)(FirmwareReadNear8(FW_NEAR_UNKNOWN_1301) & 0xfbu));
    FirmwareWriteNear8(FW_NEAR_UNKNOWN_1301, (u8)(FirmwareReadNear8(FW_NEAR_UNKNOWN_1301) & 0xfeu));
    FirmwareWriteNear8(FW_NEAR_UNKNOWN_125D, 0xffu);

    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_0180F4, 2u);
    saved_p1_bit1 = OPERATING_RESET_READ_P1_BIT1();
    OPERATING_RESET_WRITE_P1_BIT1(0u);
    saved_p1_bit0 = OPERATING_RESET_READ_P1_BIT0();
    OPERATING_RESET_WRITE_P1_BIT0(0u);
    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_01809C, 0u);
    OPERATING_RESET_SET_FLAG(0u);
    OPERATING_RESET_RESET_CHANNELS();
    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_0180AC, 0xdfu);
    do
    {
    } while((OPERATING_RESET_READ_PORT(FW_CONTROLLER_UNKNOWN_0180AC) & 0x7fu) != 0u);

    if((FirmwareReadNear8(FW_NEAR_UNKNOWN_1304) & 1u) == 1u)
        OPERATING_RESET_LOAD_PROFILE(0u);
    OPERATING_RESET_INITIALIZE_D4_D5();
    OPERATING_RESET_WRITE_P1_BIT1(saved_p1_bit1);
    OPERATING_RESET_WRITE_P1_BIT0(saved_p1_bit0);
    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_01809C, 0xffu);
    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_0180AC, 0u);
    OPERATING_RESET_TAIL();

    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_01808C, 0x87u);
    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_018080, 0u);
    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_018082, 0xb0u);
    OPERATING_RESET_RESET_PORTS();
    OPERATING_RESET_INITIALIZE_C2_D0_D3();
    OPERATING_RESET_INITIALIZE_D8_D9();
    OPERATING_RESET_CLEAR_DC_DD();
    OPERATING_RESET_SUBMIT_BYTE_WORD(0u, 0x0256u);
    OPERATING_RESET_SUBMIT_BYTE_WORD(FirmwareReadNear8(FW_NEAR_UNKNOWN_F9A8), 0x0255u);
    WriteOperatingResetWord(FW_NEAR_UNKNOWN_F994, (u16)FirmwareReadNear8(FW_NEAR_UNKNOWN_F9A8));
    OPERATING_RESET_SUBMIT_BYTE_WORD(0x80u, 0x0257u);
    OPERATING_RESET_WRITE_PORT(FW_CONTROLLER_UNKNOWN_0180C0, 0u);
    OPERATING_RESET_SUBMIT_WORD(0u, 0x024fu);
    OPERATING_RESET_WRITE_P1_BIT1(1u);
    OPERATING_RESET_WRITE_P1_BIT0(1u);
    OPERATING_RESET_WRITE_P1_BIT1(1u);
    OPERATING_RESET_WRITE_P1_BIT0(1u);
    WriteOperatingResetWord(FW_NEAR_UNKNOWN_FC2B, 0u);
    FirmwareWriteNear8(FW_NEAR_UNKNOWN_FC2D, 2u);
    FirmwareWriteNear8(FW_NEAR_UNKNOWN_FC2E, 2u);
    FirmwareWriteNear8(FW_NEAR_UNKNOWN_FC2F, 3u);
}
